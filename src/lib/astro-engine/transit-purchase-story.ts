import type { PlanetPurchaseReport, PlanetPurchaseGuidance } from "./transit-planet-purchase";
import type { CombinedTransitPurchaseResult } from "./transit-purchase-combined";
import type { TransitReport } from "./transits";

export interface StoryChapter {
  number: number;
  title: string;
  icon: string;
  story: string;
}

export interface TransitPurchaseNarrative {
  title: string;
  subtitle: string;
  introQuote: string;
  chapters: StoryChapter[];
  closingAdvice: string;
}

const RASHI_NAMES = [
  "मेष (Aries)",
  "वृषभ (Taurus)",
  "मिथुन (Gemini)",
  "कर्क (Cancer)",
  "सिंह (Leo)",
  "कन्या (Virgo)",
  "तुला (Libra)",
  "वृश्चिक (Scorpio)",
  "धनु (Sagittarius)",
  "मकर (Capricorn)",
  "कुंभ (Aquarius)",
  "मीन (Pisces)",
];

export function generateTransitPurchaseNarrative({
  chart,
  transitReport,
  guidance,
  planetReport,
}: {
  chart: any;
  transitReport: TransitReport;
  guidance: CombinedTransitPurchaseResult;
  planetReport: PlanetPurchaseReport;
}): TransitPurchaseNarrative {
  const moonTransit = transitReport.planets.find((p) => p.planet === "Moon");
  const moonRashi = moonTransit?.rashiName || "गोचर चंद्रमा";
  const moonHouse = moonTransit?.houseFromBase || 1;

  // Best and worst planets
  const bestPlanet = planetReport.best;
  const worstPlanet = planetReport.worst;

  // Find all planets with score >= 60
  const strongPlanets = planetReport.planets.filter((p) => p.score >= 58);
  const weakPlanets = planetReport.planets.filter((p) => p.score < 45 || p.verdict === "AVOID" || p.verdict === "WAIT");

  // Sade Sati status
  const sadeSati = guidance.sadeSatiZone;

  // Intro Quote
  const introQuote =
    guidance.overall === "BUY"
      ? "“जब ब्रह्मांड के द्वार खुले हों और चंद्रमा की शीतलता आपके विवेक को संवार रही हो, तब विवेकपूर्ण ढंग से किया गया निवेश केवल वस्तु नहीं लाता—वह घर में लक्ष्मी और संतोष की प्रतिष्ठा करता है।”"
      : guidance.overall === "BUY_CAREFULLY"
      ? "“खरीदारी केवल धन का व्यय नहीं, बल्कि अपने भविष्य के साथ किया गया एक मौन समझौता है। आज का आकाश अनुमति तो दे रहा है, लेकिन शर्त एक ही है—हर कागज़, हर गारंटी और हर आवश्यकता को दो बार परखें।”"
      : guidance.overall === "WAIT"
      ? "“प्रतीक्षा कभी कमज़ोरी नहीं होती; यह शिकारी की तरह सही क्षण की प्रतीक्षा करने का विवेक है। आज के आकाशीय स्पंदन आपको थोड़ा रुकने और अपनी प्राथमिकताओं को दोबारा तौलने का संकेत दे रहे हैं।”"
      : "“जब आकाश में तूफान हो, तो नौका को तट पर ही बांधे रखना बुद्धिमानी है। आज का गोचर आपको अनावश्यक जोखिम, भावनात्मक ख़र्च और पछतावे से बचाने के लिए एक ढाल बनकर खड़ा है।”";

  // Chapter 1: The Cosmic Mood & Your Mind
  let moonMoodDesc = "";
  if ([1, 4, 7, 10].includes(moonHouse)) {
    moonMoodDesc = `आज चंद्रमा आपके केंद्र भाव (भाव ${moonHouse}) में संचरण कर रहा है। आपका मन क्रियाशील, निर्णय लेने में सक्षम और सामाजिक प्रतिष्ठा के प्रति सजग है। ऐसे समय में आप जो भी चुनते हैं, वह आपके व्यक्तित्व और जीवनशैली का सीधा विस्तार बन जाता है।`;
  } else if ([5, 9].includes(moonHouse)) {
    moonMoodDesc = `आज चंद्रमा त्रिकोण भाव (भाव ${moonHouse}) में गोचरस्थ है, जो ज्ञान, अंतर्ज्ञान और दैवीय कृपा का संकेत है। आपका आंतरिक विवेक जाग्रत है, इसलिए उच्च शिक्षा, धर्म, सात्विक आभूषण और दीर्घकालिक मूल्यवान वस्तुओं की खरीद में आपका अंतर्मन सही दिशा पकड़ेगा।`;
  } else if ([6, 8, 12].includes(moonHouse)) {
    moonMoodDesc = `आज चंद्रमा संवेदनशील भाव (भाव ${moonHouse}) से गुज़र रहा है। ज्योतिष का शाश्वत नियम है कि जब चंद्रमा 6ठे (ऋण/शत्रु), 8वें (अप्रत्याशित दबाव) या 12वें (हानि/व्यय) भाव में हो, तो व्यक्ति अक्सर मानसिक तनाव, अकेलापन या 'मूड ठीक करने' के बहाने अनावश्यक खरीदारी की ओर झुकता है। आज किसी भी बड़े वित्तीय फैसले से पहले 24 घंटे का विराम अवश्य लें।`;
  } else if ([2, 11].includes(moonHouse)) {
    moonMoodDesc = `आज चंद्रमा धन व लाभ भाव (भाव ${moonHouse}) में चमक रहा है। आपके भीतर संचय और मूल्य संवर्धन की सहज समझ बनी हुई है। आप वही सौदा हाथ में लेंगे जिससे आपके परिवार की समृद्धि या आर्थिक स्थिरता में इज़ाफ़ा हो।`;
  } else {
    moonMoodDesc = `आज चंद्रमा पराक्रम व सहज भाव (भाव ${moonHouse}) में है। मन में नए उपकरण या यात्रा से जुड़े साधन जुटाने का उत्साह रहेगा।`;
  }

  const chapter1Story = `कल्पना कीजिए कि जन्म कुंडली आपका स्थायी घर है और गोचर प्रतिदिन आपके घर की खिड़की पर आने वाली मौसम की हवा। आज आपकी खिड़की पर चंद्रमा की स्थिति ${moonRashi} में है।

${moonMoodDesc}

खरीदारी की असली शुरुआत बैंक अकाउंट से नहीं, बल्कि आपके अवचेतन मन से होती है। जब तक मन शांत न हो, तब तक दुनिया का सबसे बेहतरीन डिस्काउंट भी अंततः पश्चाताप बन जाता है। इसलिए आज कोई भी वस्तु हाथ में लेने से पहले स्वयं से यह सरल प्रश्न ज़रूर पूछें—'क्या यह मेरी वास्तविक आवश्यकता है, या केवल आज के अस्थिर मन की एक क्षणिक ज़िद?'`;

  // Chapter 2: The Auspicious Flow (Strongest Planets)
  const bestNames = strongPlanets.map((p) => `${p.hindiName} (${p.domain})`).slice(0, 3).join(", ");
  const chapter2Story = strongPlanets.length > 0
    ? `आज के आकाशीय नक्शे में कुछ ग्रह विशेष अनुग्रह के साथ मुस्कुरा रहे हैं। मुख्य रूप से ${bestNames} अनुकूल स्थिति में स्थित हैं।

विशेषकर ${bestPlanet?.hindiName || "शुभ ग्रह"} की किरणें अत्यंत स्वच्छ और सबल हैं। यदि आप ${bestPlanet?.objects.slice(0, 4).join(", ") || "सात्विक वस्तुएं"} लेने का विचार कर रहे हैं, तो आज का दिन आपके साथ खड़ा है। इन वस्तुओं में एक विशेष प्रकार का 'स्थिर प्राण' रहेगा—यानी ये चीज़ें घर में आकर टूटने-फूटने या व्यर्थ पड़े रहने के बजाय आपके दैनिक जीवन में आनंद और उत्पादकता जोड़ेंगी।

शास्त्र कहते हैं कि जिस ग्रह की रश्मियाँ उस दिन बलवान हों, उसकी वस्तुओं में किया गया निवेश व्यक्ति के भाग्य को सहजता से गति देता है। बस ध्यान रहे कि खरीदारी अपनी जेब के सामर्थ्य के भीतर हो, न कि दूसरों को चमत्कृत करने के उद्देश्य से।`
    : `आज के गोचर में अधिकांश ग्रह एक विराम की मुद्रा में हैं। कोई भी ग्रह अति-उत्साह से भरा हुआ नहीं है, जिसका अर्थ यह है कि प्रकृति आज आपको 'यथास्थिति' (Status Quo) बनाए रखने का सुझाव दे रही है। यदि कुछ लेना ही हो, तो केवल अति-आवश्यक दैनिक उपयोग की वस्तुएं ही लें।`;

  // Chapter 3: Cosmic Resistance & The Red Flags
  let chapter3Story = "";
  if (sadeSati.active) {
    chapter3Story = `हर यात्रा में एक ऐसा मोड़ आता है जहाँ सड़क पर गति कम करनी पड़ती है। आपकी कुंडली पर वर्तमान में शनिदेव का प्रभाव (${sadeSati.title}) दृष्टिगोचर है। 

शनिदेव कर्म, अनुशासन और पुरानी वस्तुओं के अधिपति हैं। साढ़े साती या कंटक शनि के दौरान सबसे बड़ा ख़तरा पुरानी गाड़ियों (Used Cars), सेकेंड-हैंड लोहे/मशीनरी, अनवेरिफाइड ज़मीन-जायदाद या किसी के छोड़े हुए चमड़े के सामान में होता है। ऐसे समय में वस्तुएं बाहर से सस्ती और आकर्षक दिखती हैं, लेकिन घर आते ही उनमें छुपे हुए लीगल पेपर्स के पेंच, बार-बार वर्कशॉप के चक्कर और जेब खाली करने वाले रिपेयर सामने आने लगते हैं।

${weakPlanets.length > 0 ? `इसके अतिरिक्त आज ${weakPlanets.map(p => p.hindiName).join(", ")} का गोचर भी कुछ खिंचाव दर्शा रहा है। इसलिए आवेश में आकर कोई बड़ा इलेक्ट्रॉनिक अपग्रेड या शेयर बाज़ार/क्रिप्टो का सट्टा लगाने से अपने हाथ पीछे रखें।` : ""}`;
  } else if (weakPlanets.length > 0) {
    chapter3Story = `आज कुछ ग्रहों के मार्ग में कॉस्मिक फ्रिक्शन (ब्रह्मांडीय प्रतिरोध) मौजूद है। विशेषकर ${weakPlanets.map(p => `${p.hindiName} (${p.planet})`).join(" और ")} आज संवेदनशील या वक्री अवस्था में हैं।

जब कोई ग्रह दबाव में होता है, तो उसकी कारक वस्तुओं के सौदों में 'छिपी हुई त्रुटियां' (Hidden Defects) रह जाती हैं। उदाहरण के लिए, यदि बुध पर दबाव हो तो फोन या लैपटॉप की वारंटी/बिल में झोल निकल सकता है; यदि मंगल पर दबाव हो तो वाहन का इंजन या ज़मीन के दस्तावेज़ में पेच फंस सकता है। ब्रह्मांड आपको मना नहीं कर रहा, बल्कि केवल यह कह रहा है—'अपनी आँखें खुली रखो और विक्रेता की बातों पर आंख मूंदकर भरोसा मत करो।'`;
  } else {
    chapter3Story = `आज कोई बहुत बड़ा नकारात्मक अवरोध नहीं है, जो एक सुखद संकेत है। फिर भी, कभी भी अत्यधिक आत्मविश्वास में आकर क्रेडिट कार्ड की सीमा लांघना उचित नहीं है। जब आकाश शांत हो, तब भी एक जागरूक उपभोक्ता की तरह रसीद, रिटर्न पॉलिसी और बजट का अनुशासन बनाए रखना ही सच्चा ज्योतिषीय विवेक है।`;
  }

  // Chapter 4: Lal Kitab's Secret Rule on Gifts & Unearned Objects
  const topLk = guidance.lalKitab[0];
  const chapter4Story = `लाल किताब केवल ग्रहों की स्थिति नहीं देखती, वह आपके घर की दहलीज पर आने वाली हर वस्तु के 'गुप्त व्याकरण' को जानती है। लाल किताब का एक बुनियादी नियम याद रखिए—'संसार में कोई भी उपहार मुफ़्त नहीं होता, हर वस्तु अपने साथ किसी न किसी ग्रह का कार्मिक भार लेकर आती है।'

${topLk ? `आज की दशा और गोचर के अनुसार: **${topLk.title}** पर विशेष ध्यान दें। ${topLk.explanation}` : "आज किसी से भी पुराना चमड़ा, जंग लगा लोहा, खराब हो चुकी इलेक्ट्रॉनिक वस्तुएं या उतरा हुआ सामान मुफ़्त में स्वीकार न करें।"}

जब आप किसी से कोई वस्तु मुफ़्त में स्वीकार करते हैं जिसका ग्रह आपकी कुंडली में पीड़ित हो, तो अनजाने में आप सामने वाले व्यक्ति का कार्मिक बोझ अपने सिर पर उठा लेते हैं। यदि कोई आपको स्नेहवश कुछ देना ही चाहे, तो प्रतीकात्मक रूप से उसे एक सिक्का या मिठाई देकर उस लेनदेन को निष्कलंक बना लें।`;

  // Final Closing Advice
  const closingAdvice = guidance.overall === "BUY"
    ? "आज का समग्र संदेश: मार्ग प्रशस्त है। अपनी आवश्यकताओं की सूची बनाएं, शुभ ग्रहों के दायरे में आने वाली वस्तुओं को प्राथमिकता दें और मन में कृतज्ञता का भाव रखकर आगे बढ़ें।"
    : guidance.overall === "BUY_CAREFULLY"
    ? "आज का समग्र संदेश: हरी झंडी है, लेकिन स्पीड-ब्रेकर के साथ। मोलभाव कीजिए, दस्तावेज़ स्वयं पढ़िए और किसी के दबाव में आकर आज 'हाँ' मत कहिए।"
    : "आज का समग्र संदेश: आज का दिन अपनी तिजोरी पर पहरा देने का है। गैर-ज़रूरी इच्छाओं को 2-3 दिन का समय दीजिए; यदि इच्छा तब भी जीवित रही, तो ब्रह्मांड स्वयं आपके लिए बेहतर अवसर तैयार करेगा।";

  return {
    title: "आज का क्रय-मुहूर्त व वस्तु व्याकरण: एक मेंटर की दृष्टि से",
    subtitle: "आकाश की चाल, आपके जन्म-चंद्रमा की ऊर्जा और आपकी जेब के बीच का जीवंत संवाद",
    introQuote,
    chapters: [
      {
        number: 1,
        title: "आकाश की वर्तमान चाल और आपका मन",
        icon: "🌙",
        story: chapter1Story,
      },
      {
        number: 2,
        title: "आज किन वस्तुओं में बह रही है प्राण-ऊर्जा",
        icon: "✨",
        story: chapter2Story,
      },
      {
        number: 3,
        title: "ब्रह्मांडीय प्रतिरोध और संभलने का संदेश",
        icon: "🛡️",
        story: chapter3Story,
      },
      {
        number: 4,
        title: "लाल किताब का गुप्त वस्तु व उपहार सूत्र",
        icon: "📜",
        story: chapter4Story,
      },
    ],
    closingAdvice,
  };
}

